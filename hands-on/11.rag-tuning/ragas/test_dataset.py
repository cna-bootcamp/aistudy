# 헬퍼 함수 (11.2 RAGAS 평가 예제가 데이터셋을 소비할 때 사용)
# ---------------------------------------------------------------------------

def get_test_dataset() -> list[dict]:
    """전체 테스트 케이스 리스트(각 원소: question/ground_truth/expected_source 등)를 반환함."""
    return TEST_CASES


def get_questions() -> list[str]:
    """모든 테스트 케이스의 question만 추출하여 리스트로 반환함 (RAG 실행 입력용)."""
    # 리스트 컴프리헨션: 각 케이스 dict에서 "question" 값만 순서대로 모음
    return [case["question"] for case in TEST_CASES]


def get_ground_truths() -> list[str]:
    """모든 테스트 케이스의 ground_truth만 추출하여 리스트로 반환함 (정답 비교용)."""
    return [case["ground_truth"] for case in TEST_CASES]


# ---------------------------------------------------------------------------
# 데이터셋 확인용 실행 코드
# ---------------------------------------------------------------------------

def main() -> None:
    """총 케이스 수·난이도 분포·질문 목록을 출력하여 데이터셋 구성을 한눈에 확인함."""
    cases = get_test_dataset()
    print(f"총 테스트 케이스 수: {len(cases)}개")

    # 난이도별 개수 집계: difficulty 키가 없으면 "(미지정)"으로 분류함
    difficulty_count: dict[str, int] = {}
    for case in cases:
        level = case.get("difficulty", "(미지정)")
        difficulty_count[level] = difficulty_count.get(level, 0) + 1
    # 난이도 분포를 easy→medium→hard 순서로 정렬해 출력함
    order = {"easy": 0, "medium": 1, "hard": 2}
    summary = ", ".join(
        f"{level} {count}개"
        for level, count in sorted(difficulty_count.items(), key=lambda x: order.get(x[0], 99))
    )
    print(f"난이도 분포: {summary}")

    print("\n[질문 목록]")
    for index, question in enumerate(get_questions(), start=1):
        print(f"  {index:>2}. {question}")


# 이 파일을 직접 실행할 때만 main()을 수행함 (import 시 미실행)
if __name__ == "__main__":
    main()
